var (
	ErrInvalid     = errors.New("invalid Walmart listing material")
	ErrUnavailable = errors.New("Walmart capability unavailable")
	ErrUnknown     = errors.New("Walmart write outcome unknown")
	ErrRejected    = errors.New("Walmart authorization rejected")
)

const (
	FullFeed     = "MP_ITEM"
	MatchFeed    = "MP_ITEM_MATCH"
	MaxFeedBytes = 2 << 20
	MaxSKUs      = 1000
)

type RuleSelection struct {
	FeedType    string `json:"feedType"`
	Version     string `json:"version"`
	ProductType string `json:"productType"`
}

func (s RuleSelection) Valid() bool {
	return (s.FeedType == FullFeed || s.FeedType == MatchFeed) && len(s.Version) > 0 && len(s.Version) <= 128 && (s.FeedType == MatchFeed || len(s.ProductType) > 0) && len(s.ProductType) <= 200
}

type FeedHeader struct {
	BusinessUnit   string `json:"businessUnit,omitempty"`
	Locale         string `json:"locale"`
	Version        string `json:"version"`
	SellingChannel string `json:"sellingChannel,omitempty"`
	ProcessMode    string `json:"processMode,omitempty"`
	Subset         string `json:"subset,omitempty"`
	SubCategory    string `json:"subCategory,omitempty"`
	FeedType       string `json:"feedType,omitempty"`
}
type RuleSnapshot struct {
	Selection  RuleSelection `json:"selection"`
	Header     FeedHeader    `json:"header"`
	Schema     []byte        `json:"schema"`
	Partial    bool          `json:"partial"`
	ObservedAt time.Time     `json:"observedAt"`
}

func Hash(v any) string {
	b, _ := json.Marshal(v)
	h := sha256.Sum256(b)
	return hex.EncodeToString(h[:])
}
func (r RuleSnapshot) Hash() string {
	var schema any
	if json.Unmarshal(r.Schema, &schema) != nil {
		return ""
	}
	return Hash(struct {
		Selection RuleSelection
		Header    FeedHeader
		Schema    any
	}{r.Selection, r.Header, schema})
}
func (r RuleSnapshot) compile() (*jsonschema.Schema, error) {
	if !r.Selection.Valid() || r.Partial || len(r.Schema) == 0 || len(r.Schema) > MaxFeedBytes || r.Header.Version != r.Selection.Version || r.Header.Locale != "en" || r.Header.BusinessUnit != "" && r.Header.BusinessUnit != "WALMART_US" {
		return nil, ErrInvalid
	}
	var doc any
	if json.Unmarshal(r.Schema, &doc) != nil {
		return nil, ErrInvalid
	}
	root, ok := doc.(map[string]any)
	if !ok || root["$schema"] != "http://json-schema.org/draft-07/schema#" && root["$schema"] != "https://json-schema.org/draft-07/schema#" {
		return nil, ErrInvalid
	}
	c := jsonschema.NewCompiler()
	c.DefaultDraft(jsonschema.Draft7)
	c.UseLoader(jsonschema.SchemeURLLoader{})
	const location = "urn:task-processor:walmart:spec"
	if err := c.AddResource(location, doc); err != nil {
		return nil, ErrInvalid
	}
	s, e := c.Compile(location)
	if e != nil {
		return nil, ErrInvalid
	}
	return s, nil
}
func (r RuleSnapshot) Validate() error { _, e := r.compile(); return e }

type Identifier struct {
	Type string `json:"productIdType"`
	ID   string `json:"productId"`
}
type SKUInput struct {
	SourceSKUKey   string      `json:"sourceSKUKey"`
	Identifier     Identifier  `json:"identifier"`
	Condition      string      `json:"condition"`
	Price          json.Number `json:"price"`
	ShippingWeight json.Number `json:"shippingWeight"`
	// Only the explicit Orderable/Item and selected Visible product type slots
	// are extensible. The complete assembled Feed must pass the pinned schema.
	Attributes map[string]any `json:"attributes,omitempty"`
	Visible    map[string]any `json:"visible,omitempty"`
}
type DraftInput struct {
	Selection  RuleSelection `json:"selection"`
	SKUs       []SKUInput    `json:"skus"`
	RepairFrom string        `json:"repairFrom,omitempty"`
	RepairSKUs []string      `json:"repairSKUs,omitempty"`
}
type SKUBinding struct {
	SourceSKUKey string `json:"sourceSKUKey"`
	SellerSKU    string `json:"sellerSKU"`
}
type Draft struct {
	Selection RuleSelection `json:"selection"`
	SKUs      []SKUBinding  `json:"skus"`
	// []byte is encoded as Base64 by JSON persistence. JSONB must never
	// rewrite the exact approved wire bytes or their fingerprint.
	Payload   []byte `json:"payload"`
	WireHash  string `json:"wireHash"`
	RulesHash string `json:"rulesHash"`
}

var identifier = regexp.MustCompile(`^[A-Za-z0-9._-]{1,128}$`)

// The canonical Store grant ID is random and retained across refresh,
// disconnect and re-consent. Its namespace must never be regenerated by a
// Target edit, application replacement or another upload operation.
func SKUNamespace(merchantHash, grantID string) string {
	return Hash([]string{"walmart-permanent-sku-namespace-v1", merchantHash, grantID})
}
func SellerSKU(merchant, product, source string) string {
	return "tp-" + Hash([]string{"walmart-us-offer-v1", merchant, product, source})[:40]
}
func BuildDraft(in DraftInput, r RuleSnapshot, merchant, product string, sources []string) (Draft, error) {
	var out Draft
	if in.Selection != r.Selection || merchant == "" || product == "" || len(in.SKUs) == 0 || len(in.SKUs) > MaxSKUs || len(sources) != len(in.SKUs) {
		return out, ErrInvalid
	}
	compiled, e := r.compile()
	if e != nil {
		return out, e
	}
	allowed := map[string]bool{}
	for _, s := range sources {
		if s == "" || allowed[s] {
			return out, ErrInvalid
		}
		allowed[s] = true
	}
	items := make([]any, 0, len(in.SKUs))
	out.Selection = in.Selection
	out.RulesHash = r.Hash()
	for _, s := range in.SKUs {
		if !allowed[s.SourceSKUKey] || !identifier.MatchString(s.Identifier.ID) || strings.EqualFold(s.Identifier.ID, "CUSTOM") || !supportedIdentifier(s.Identifier.Type) || !boundedSetupAttributes(s.Attributes) || !boundedSetupAttributes(s.Visible) || s.Condition == "" {
			return Draft{}, ErrInvalid
		}
		delete(allowed, s.SourceSKUKey)
		price, e := s.Price.Float64()
		if e != nil || price <= 0 {
			return Draft{}, ErrInvalid
		}
		weight, e := s.ShippingWeight.Float64()
		if e != nil || weight <= 0 {
			return Draft{}, ErrInvalid
		}
		sku := SellerSKU(merchant, product, s.SourceSKUKey)
		fields := map[string]any{}
		for k, v := range s.Attributes {
			switch k {
			case "sku", "productIdentifiers", "price", "condition", "ShippingWeight", "specProductType":
				return Draft{}, ErrInvalid
			}
			fields[k] = v
		}
		fields["sku"] = sku
		fields["productIdentifiers"] = s.Identifier
		fields["price"] = s.Price
		fields["condition"] = s.Condition
		fields["ShippingWeight"] = s.ShippingWeight
		if in.Selection.FeedType == MatchFeed {
			if len(s.Visible) > 0 {
				return Draft{}, ErrInvalid
			}
			items = append(items, map[string]any{"Item": fields})
		} else {
			fields["specProductType"] = in.Selection.ProductType
			items = append(items, map[string]any{"Orderable": fields, "Visible": map[string]any{in.Selection.ProductType: s.Visible}})
		}
		out.SKUs = append(out.SKUs, SKUBinding{s.SourceSKUKey, sku})
	}
	if in.RepairFrom != "" || len(in.RepairSKUs) > 0 {
		if in.RepairFrom == "" || len(in.RepairFrom) > 128 || len(in.RepairSKUs) == 0 {
			return Draft{}, ErrInvalid
		}
		selected := map[string]bool{}
		for _, s := range in.RepairSKUs {
			if selected[s] {
				return Draft{}, ErrInvalid
			}
			selected[s] = true
		}
		subset := []any{}
		bindings := []SKUBinding{}
		for i, b := range out.SKUs {
			if selected[b.SellerSKU] {
				subset = append(subset, items[i])
				bindings = append(bindings, b)
				delete(selected, b.SellerSKU)
			}
		}
		if len(selected) > 0 {
			return Draft{}, ErrInvalid
		}
		items = subset
		out.SKUs = bindings
	}
	payload, e := json.Marshal(struct {
		Header FeedHeader `json:"MPItemFeedHeader"`
		Items  []any      `json:"MPItem"`
	}{r.Header, items})
	if e != nil || len(payload) > MaxFeedBytes {
		return Draft{}, ErrInvalid
	}
	var value any
	dec := json.NewDecoder(bytes.NewReader(payload))
	dec.UseNumber()
	if dec.Decode(&value) != nil {
		return Draft{}, ErrInvalid
	}
	// The library accepts ordinary float64 decoded JSON values.
	if json.Unmarshal(payload, &value) != nil || compiled.Validate(value) != nil {
		return Draft{}, ErrInvalid
	}
	out.Payload = payload
	h := sha256.Sum256(payload)
	out.WireHash = hex.EncodeToString(h[:])
	return out, nil
}
func (d Draft) ExpectedSKUs() []string {
	out := make([]string, 0, len(d.SKUs))
	for _, s := range d.SKUs {
		out = append(out, s.SellerSKU)
	}
	sort.Strings(out)
	return out
}

type ItemError struct {
	Code        string `json:"code"`
	Field       string `json:"field,omitempty"`
	Description string `json:"description,omitempty"`
}
type ItemResult struct {
	SKU                   string      `json:"sku"`
	IngestionStatus       string      `json:"ingestionStatus"`
	PublicationStatus     string      `json:"publishedStatus,omitempty"`
	PublicationObservedAt *time.Time  `json:"publicationObservedAt,omitempty"`
	LifecycleStatus       string      `json:"lifecycleStatus,omitempty"`
	Availability          string      `json:"availability,omitempty"`
	ItemID                string      `json:"itemId,omitempty"`
	Errors                []ItemError `json:"errors,omitempty"`
}
type FeedObservation struct {
	FeedID         string       `json:"feedId"`
	FeedStatus     string       `json:"feedStatus"`
	Received       int          `json:"itemsReceived"`
	Succeeded      int          `json:"itemsSucceeded"`
	Failed         int          `json:"itemsFailed"`
	Processing     int          `json:"itemsProcessing"`
	Items          []ItemResult `json:"items"`
	Partial        bool         `json:"partial"`
	ResponseHashes []string     `json:"responseHashes"`
	ObservedAt     time.Time    `json:"observedAt"`
}

func (o FeedObservation) CompleteFor(expected []string) bool {
	if o.FeedID == "" || o.Partial || len(expected) == 0 || o.Received < 0 || o.Succeeded < 0 || o.Failed < 0 || o.Processing < 0 {
		return false
	}
	set := map[string]bool{}
	for _, s := range expected {
		if s == "" || set[s] {
			return false
		}
		set[s] = true
	}
	if o.FeedStatus == "ERROR" {
		return o.Succeeded == 0 && o.Processing == 0 && len(o.Items) == 0 && (o.Received == 0 || o.Received == len(expected)) && (o.Failed == 0 || o.Failed == len(expected))
	}
	if o.FeedStatus != "RECEIVED" && o.FeedStatus != "INPROGRESS" && o.FeedStatus != "PROCESSED" || len(o.Items) != len(expected) || o.Received != len(expected) || o.Received != o.Succeeded+o.Failed+o.Processing {
		return false
	}
	succeeded, failed, processing := 0, 0, 0
	for _, s := range o.Items {
		if !set[s.SKU] {
			return false
		}
		delete(set, s.SKU)
		switch s.IngestionStatus {
		case "SUCCESS":
			succeeded++
		case "DATA_ERROR", "SYSTEM_ERROR", "TIMEOUT_ERROR":
			failed++
		case "INPROGRESS":
			processing++
		default:
			return false
		}
	}
	return len(set) == 0 && succeeded == o.Succeeded && failed == o.Failed && processing == o.Processing
}
func (o FeedObservation) AllowsRepair(expected, repair []string) bool {
	if !o.CompleteFor(expected) || len(repair) == 0 || o.FeedStatus != "PROCESSED" && o.FeedStatus != "ERROR" {
		return false
	}
	failed := map[string]bool{}
	if o.FeedStatus == "ERROR" {
		for _, s := range expected {
			failed[s] = true
		}
	} else {
		for _, s := range o.Items {
			if s.IngestionStatus != "SUCCESS" && s.IngestionStatus != "DATA_ERROR" {
				return false
			}
			if s.IngestionStatus == "DATA_ERROR" {
				failed[s.SKU] = true
			}
		}
	}
	seen := map[string]bool{}
	for _, s := range repair {
		if !failed[s] || seen[s] {
			return false
		}
		seen[s] = true
	}
	return true
}
func (d Draft) ValidateWire() error {
	h := sha256.Sum256(d.Payload)
	if len(d.Payload) == 0 || len(d.Payload) > MaxFeedBytes || hex.EncodeToString(h[:]) != d.WireHash || !d.Selection.Valid() || len(d.SKUs) == 0 {
		return ErrInvalid
	}
	return nil
}
func supportedIdentifier(value string) bool {
	switch value {
	case "GTIN", "UPC", "EAN", "ISBN", "WPID":
		return true
	}
	return false
}

// The spec admits optional capabilities outside this release. Schema validity
// alone cannot authorize exemption applications, identity changes or repricing.
func boundedSetupAttributes(value any) bool {
	switch v := value.(type) {
	case map[string]any:
		for key, item := range v {
			normalized := strings.ToLower(strings.ReplaceAll(key, "_", ""))
			switch normalized {
			case "automatepricing", "repricerstrategy", "fulfillmenttype", "iswalmartfulfilled", "skuupdate", "productidupdate", "gtinexemption":
				return false
			}
			if !boundedSetupAttributes(item) {
				return false
			}
		}
	case []any:
		for _, item := range v {
			if !boundedSetupAttributes(item) {
				return false
			}
		}
	}
	return true
}
